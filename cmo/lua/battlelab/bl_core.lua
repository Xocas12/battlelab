BL.REQUIRED_API = {
  "ScenEdit_AddUnit", "ScenEdit_DeleteUnit", "ScenEdit_GetUnit", "ScenEdit_SetUnit",
  "ScenEdit_SetUnitSide", "ScenEdit_AssignUnitToMission", "ScenEdit_GetMission",
  "ScenEdit_SetMission", "ScenEdit_GetReferencePoints", "ScenEdit_CurrentTime",
  "ScenEdit_SetKeyValue", "ScenEdit_GetKeyValue", "ScenEdit_AddExplosion",
  "VP_GetSides", "VP_GetSide",
}

function BL.selftest(plugin)
  local ok_all = true
  local function check(label, ok, detail)
    print(("[selftest] %-44s %s %s"):format(label, ok and "OK  " or "FAIL", detail or ""))
    ok_all = ok_all and ok
  end
  for _, fn in ipairs(BL.REQUIRED_API) do check("API " .. fn, type(rawget(_G, fn)) == "function") end
  local folder = rawget(_G, "_scenariofolder_") or ""
  local f = try_open(folder .. "/battlelab_selftest.tmp", "w")
  if f then f:write("ok"); f:close() end
  check("file output (else KeyStore fallback)", true, f and "file" or "keystore")
  ScenEdit_SetKeyValue("bl_selftest", "42")
  check("KeyStore round trip", ScenEdit_GetKeyValue("bl_selftest") == "42")
  local units = BL.all_units()
  check("units visible", #units > 0, "(" .. #units .. ")")
  local tpl = BL.snapshot()
  local with_dbid = 0
  for _, r in ipairs(tpl) do if r.dbid then with_dbid = with_dbid + 1 end end
  check("snapshot has DBIDs", with_dbid == #tpl, ("(%d/%d)"):format(with_dbid, #tpl))
  if plugin and plugin.selftest then
    for _, c in ipairs(plugin.selftest(tpl)) do check(c[1], c[2], c[3]) end
  end
  print("[selftest] " .. (ok_all and "ALL CHECKS PASSED" or "SOME CHECKS FAILED - see above"))
  return ok_all
end

